-- OpenRings Community schema (PostgreSQL 12+). Safe to run repeatedly.

CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL,
  email         TEXT,
  password_hash TEXT,
  role          TEXT NOT NULL DEFAULT 'member'
                CHECK (role IN ('member', 'support', 'admin', 'ai', 'persona')),
  title         TEXT,
  bio           TEXT NOT NULL DEFAULT '',
  location      TEXT NOT NULL DEFAULT '',
  website       TEXT NOT NULL DEFAULT '',
  persona_json  TEXT,
  is_active     INTEGER NOT NULL DEFAULT 1,
  is_banned     INTEGER NOT NULL DEFAULT 0,
  post_count    INTEGER NOT NULL DEFAULT 0,
  like_count    INTEGER NOT NULL DEFAULT 0,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at  TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower ON users (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE IF NOT EXISTS sessions (
  id         TEXT PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions (user_id);

CREATE TABLE IF NOT EXISTS categories (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  sort_order  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS forums (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id  INTEGER NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  slug         TEXT NOT NULL UNIQUE,
  title        TEXT NOT NULL,
  description  TEXT NOT NULL DEFAULT '',
  icon         TEXT NOT NULL DEFAULT 'chat',
  sort_order   INTEGER NOT NULL DEFAULT 0,
  staff_only   INTEGER NOT NULL DEFAULT 0,
  ai_enabled   INTEGER NOT NULL DEFAULT 1,
  seed_weight  INTEGER NOT NULL DEFAULT 1,
  thread_count INTEGER NOT NULL DEFAULT 0,
  post_count   INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS threads (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  forum_id          INTEGER NOT NULL REFERENCES forums(id),
  user_id           INTEGER NOT NULL REFERENCES users(id),
  title             TEXT NOT NULL,
  slug              TEXT NOT NULL,
  is_pinned         INTEGER NOT NULL DEFAULT 0,
  is_locked         INTEGER NOT NULL DEFAULT 0,
  is_solved         INTEGER NOT NULL DEFAULT 0,
  solution_post_id  INTEGER,
  ai_enabled        INTEGER NOT NULL DEFAULT 1,
  is_seeded         INTEGER NOT NULL DEFAULT 0,
  view_count        INTEGER NOT NULL DEFAULT 0,
  reply_count       INTEGER NOT NULL DEFAULT 0,
  last_post_id      INTEGER,
  last_post_at      TIMESTAMPTZ,
  last_post_user_id INTEGER,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at        TIMESTAMPTZ,
  title_search      TSVECTOR GENERATED ALWAYS AS (to_tsvector('english', coalesce(title, ''))) STORED
);
CREATE INDEX IF NOT EXISTS threads_forum ON threads (forum_id, last_post_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS threads_recent ON threads (last_post_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS threads_user ON threads (user_id);
CREATE INDEX IF NOT EXISTS threads_title_search ON threads USING GIN (title_search);

CREATE TABLE IF NOT EXISTS posts (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id  INTEGER NOT NULL REFERENCES threads(id),
  user_id    INTEGER NOT NULL REFERENCES users(id),
  body       TEXT NOT NULL,
  body_html  TEXT NOT NULL,
  is_ai      INTEGER NOT NULL DEFAULT 0,
  like_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ,
  deleted_at TIMESTAMPTZ,
  search     TSVECTOR GENERATED ALWAYS AS (to_tsvector('english', coalesce(body, ''))) STORED
);
CREATE INDEX IF NOT EXISTS posts_thread ON posts (thread_id, id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS posts_user ON posts (user_id, id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS posts_search ON posts USING GIN (search);

CREATE TABLE IF NOT EXISTS post_likes (
  post_id    INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (post_id, user_id)
);

CREATE TABLE IF NOT EXISTS jobs (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type       TEXT NOT NULL,
  payload    JSONB NOT NULL DEFAULT '{}',
  status     TEXT NOT NULL DEFAULT 'queued'
             CHECK (status IN ('queued', 'running', 'done', 'skipped', 'failed')),
  run_at     TIMESTAMPTZ NOT NULL,
  attempts   INTEGER NOT NULL DEFAULT 0,
  last_error TEXT,
  result     JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS jobs_due ON jobs (status, run_at);

CREATE TABLE IF NOT EXISTS scheduled_posts (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_date   TEXT NOT NULL,
  forum_id    INTEGER NOT NULL REFERENCES forums(id),
  persona_id  INTEGER NOT NULL REFERENCES users(id),
  title       TEXT NOT NULL,
  body        TEXT NOT NULL,
  topic_hint  TEXT,
  status      TEXT NOT NULL DEFAULT 'pending'
              CHECK (status IN ('pending', 'approved', 'published', 'rejected', 'failed')),
  publish_at  TIMESTAMPTZ NOT NULL,
  thread_id   INTEGER,
  error       TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS scheduled_due ON scheduled_posts (status, publish_at);

CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- ---- Support team: duty roster and reply drafts ----------------------------------
ALTER TABLE users ADD COLUMN IF NOT EXISTS on_duty INTEGER NOT NULL DEFAULT 0;

-- Drafted replies wait here until a support engineer reviews and posts them.
CREATE TABLE IF NOT EXISTS reply_drafts (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id        INTEGER NOT NULL REFERENCES threads(id),
  reply_to_post_id INTEGER,
  body             TEXT NOT NULL,
  assigned_to      INTEGER REFERENCES users(id),
  status           TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'posted', 'discarded')),
  post_id          INTEGER,
  posted_as        INTEGER REFERENCES users(id),
  reviewed_by      INTEGER REFERENCES users(id),
  model            TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS reply_drafts_one_pending ON reply_drafts (thread_id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS reply_drafts_queue ON reply_drafts (status, assigned_to, created_at);
